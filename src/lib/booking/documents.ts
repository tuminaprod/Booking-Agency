import type { Booking } from "@/lib/models";
import { addDays } from "@/lib/dates";
import { formatDateLong, formatMoney, guestsLabel } from "@/lib/format";

/** Client-side document generation for confirmations (calendar file + printable receipt). */

const escapeIcs = (s: string) => s.replace(/[\\,;]/g, (m) => `\\${m}`).replace(/\n/g, "\\n");
const icsDate = (d: string) => d.replace(/-/g, "");

export function bookingToIcs(b: Booking): string {
  const end = b.type === "hotel" ? b.endDate : addDays(b.endDate, 1);
  const stamp = new Date().toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//Oriel//Bookings//EN",
    "CALSCALE:GREGORIAN",
    "BEGIN:VEVENT",
    `UID:${b.reference}@oriel.example`,
    `DTSTAMP:${stamp}`,
    `DTSTART;VALUE=DATE:${icsDate(b.startDate)}`,
    `DTEND;VALUE=DATE:${icsDate(end)}`,
    `SUMMARY:${escapeIcs(`${b.item.title} — Oriel ${b.reference}`)}`,
    `LOCATION:${escapeIcs(b.item.address ?? b.item.destinationName)}`,
    `DESCRIPTION:${escapeIcs(`Confirmation ${b.reference}\n${b.item.roomName ?? b.item.timeSlot ?? ""}\n${guestsLabel(b.guests.adults, b.guests.children)}`)}`,
    "END:VEVENT",
    "END:VCALENDAR",
  ];
  return lines.join("\r\n");
}

const escapeHtml = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

export function bookingToHtml(b: Booking): string {
  const row = (k: string, v: string) => `<tr><th>${k}</th><td>${escapeHtml(v)}</td></tr>`;
  const lines = b.price.lines.map((l) => `<tr><td>${escapeHtml(l.label)}${l.payableAt === "property" ? " (pay at property)" : ""}</td><td class="r">${l.amount < 0 ? "−" : ""}${formatMoney(Math.abs(l.amount), "USD", { cents: true })}</td></tr>`).join("");
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Oriel booking ${escapeHtml(b.reference)}</title>
<style>body{font:15px/1.5 system-ui,sans-serif;color:#0f1b2d;max-width:720px;margin:40px auto;padding:0 20px}h1{font-family:Georgia,serif;font-weight:600}table{width:100%;border-collapse:collapse;margin:16px 0}th,td{text-align:left;padding:8px 0;border-bottom:1px solid #e5dfd4;vertical-align:top}th{width:40%;color:#566070;font-weight:500}.r{text-align:right}.total td{font-weight:700;font-size:17px}.ref{font-size:22px;letter-spacing:.08em;color:#a16207}</style></head><body>
<p>ORIEL</p><h1>Booking confirmation</h1><p class="ref">${escapeHtml(b.reference)}</p>
<table>${row("Booking", b.item.title)}${row("Destination", b.item.destinationName)}${b.item.roomName ? row("Room", b.item.roomName) : ""}${b.item.timeSlot ? row("Time", b.item.timeSlot) : ""}${row(b.type === "hotel" ? "Check-in" : "Start", formatDateLong(b.startDate))}${row(b.type === "hotel" ? "Check-out" : "End", formatDateLong(b.endDate))}${row("Guests", guestsLabel(b.guests.adults, b.guests.children, b.type === "hotel" ? b.guests.rooms : undefined))}${row("Lead guest", `${b.leadGuest.firstName} ${b.leadGuest.lastName} · ${b.leadGuest.email}`)}${row("Payment", `${b.payment.cardBrand.toUpperCase()} •••• ${b.payment.last4} — ${b.payment.status}`)}${row("Cancellation", b.cancellation.summary)}</table>
<h2>Price breakdown</h2><table>${lines}<tr class="total"><td>Total</td><td class="r">${formatMoney(b.price.total, "USD", { cents: true })}</td></tr><tr><td>Paid now</td><td class="r">${formatMoney(b.price.dueNow, "USD", { cents: true })}</td></tr>${b.price.dueAtProperty ? `<tr><td>Due at property</td><td class="r">${formatMoney(b.price.dueAtProperty, "USD", { cents: true })}</td></tr>` : ""}</table>
<p style="color:#566070;font-size:13px">Demonstration document generated by Oriel. All properties and bookings are fictional.</p></body></html>`;
}

export function downloadFile(filename: string, content: string, type: string) {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
