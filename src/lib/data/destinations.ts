import type { CountryCode, Destination, TravelCategory } from "@/lib/models";
import { img, type PhotoKey } from "./photos";

/**
 * Destination database — Tunisia (TN) and Algeria (DZ) only.
 * Coordinates are the real approximate centre of each place (WGS84).
 * Every destination belongs to a region of its own country (lib/geo/countries.ts).
 */

const TN_FACTS = { language: "Arabic (Tunisian), French widely spoken", timezone: "CET (UTC+1)" };
const DZ_FACTS = { language: "Arabic, Tamazight; French widely spoken", timezone: "CET (UTC+1)" };

interface Input {
  slug: string;
  name: string;
  country: CountryCode;
  region: string;
  city?: string;
  lat: number;
  lng: number;
  tagline: string;
  description: string[];
  hero: [PhotoKey, string];
  gallery?: [PhotoKey, string][];
  popularity: number;
  best: [string, string];
  gettingThere: string;
  neighborhoods?: [string, string][];
  todo: string[];
  tips: string[];
  itineraries?: { title: string; days: number; summary: string; tripSlug?: string }[];
  related: string[];
  categories: TravelCategory[];
}

const id = (country: CountryCode, slug: string) => `dst-${country.toLowerCase()}-${slug}`;

function d(i: Input): Destination {
  return {
    id: id(i.country, i.slug),
    slug: i.slug,
    name: i.name,
    countryCode: i.country,
    regionId: i.region,
    city: i.city ?? i.name,
    status: "active",
    tagline: i.tagline,
    description: i.description,
    heroImage: img(...i.hero),
    gallery: (i.gallery ?? []).map(([k, a]) => img(k, a)),
    popularity: i.popularity,
    coordinates: { lat: i.lat, lng: i.lng },
    bestTimeToVisit: { months: i.best[0], summary: i.best[1] },
    facts: { ...(i.country === "TN" ? TN_FACTS : DZ_FACTS), gettingThere: i.gettingThere },
    neighborhoods: (i.neighborhoods ?? []).map(([name, description]) => ({ name, description })),
    thingsToDo: i.todo,
    travelTips: i.tips,
    itineraries: i.itineraries ?? [],
    relatedIds: i.related.map((s) => id(i.country, s)),
    categories: i.categories,
  };
}

