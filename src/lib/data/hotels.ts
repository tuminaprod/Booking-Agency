export const FREE = (days: number): CancellationPolicy => ({
  type: "free",
  freeUntilDays: days,
  summary: `Free cancellation until ${days} day${days === 1 ? "" : "s"} before arrival`,
});
export const PARTIAL = (days: number, pct: number): CancellationPolicy => ({
  type: "partial",
  freeUntilDays: days,
  refundPercentAfter: pct,
  summary: `Free cancellation until ${days} days before arrival; ${pct}% refund after`,
});
export const NONREF: CancellationPolicy = {
  type: "non-refundable",
  summary: "Non-refundable — lowest price, no changes",
};

interface RoomInput {
  name: string;
  description: string;
  photos: [PhotoKey, string][];
  beds: [BedType, number][];
  adults: number;
  children?: number;
  size: number;
  view?: string;
  amenities: string[];
  breakfast?: boolean;
  cancel: CancellationPolicy;
  price: number;
  inventory?: number;
}

interface HotelInput {
  key: string;
  name: string;
  dest: string;
  type: PropertyType;
  stars: Hotel["stars"];
  rating: number;
  reviews: number;
  neighborhood: string;
  address: string;
  offset: [number, number];
  distance: number;
  short: string;
  description: string[];
  highlights: string[];
  photos: [PhotoKey, HotelImageCategory, string][];
  amenities: AmenityId[];
  nearby: NearbyPlace[];
  rooms: RoomInput[];
  badges?: HotelBadge[];
  popularity: number;
  categories: TravelCategory[];
  taxRate: number;
  fees?: Omit<MandatoryFee, "id">[];
  deal?: HotelDeal;
  checkIn?: string;
  checkOut?: string;
  pets?: string;
  children?: string;
  phone: string;
  extraNotes?: string[];
}

const COMMON_ROOM = ["Free Wi-Fi", "Air conditioning", "Safe", "Premium toiletries"];

function build(input: HotelInput): Hotel {
  const destination = DESTINATIONS.find((d) => d.slug === input.dest);
  if (!destination) throw new Error(`Unknown destination ${input.dest}`);
  const id = `htl-${input.key}`;
  const slug = input.key;
  const rooms: HotelRoom[] = input.rooms.map((r, i) => ({
    id: `${id}-r${i + 1}`,
    hotelId: id,
    name: r.name,
    description: r.description,
    images: r.photos.map(([k, alt]) => ({ src: photoUrl(k), alt })),
    beds: r.beds.map(([type, count]) => ({ type, count })),
    maxAdults: r.adults,
    maxChildren: r.children ?? 0,
    sizeSqm: r.size,
    view: r.view,
    amenities: [...r.amenities, ...COMMON_ROOM],
    breakfastIncluded: r.breakfast ?? false,
    cancellation: r.cancel,
    basePrice: r.price,
    inventory: r.inventory ?? 6,
  }));
  return {
    id,
    slug,
    name: input.name,
    destinationId: destination.id,
    propertyType: input.type,
    stars: input.stars,
    rating: input.rating,
    reviewCount: input.reviews,
    address: input.address,
    neighborhood: input.neighborhood,
    coordinates: {
      lat: +(destination.coordinates.lat + input.offset[0]).toFixed(5),
      lng: +(destination.coordinates.lng + input.offset[1]).toFixed(5),
    },
    distanceFromCenterKm: input.distance,
    shortDescription: input.short,
    description: input.description,
    highlights: input.highlights,
    images: input.photos.map(([k, category, alt], i) => ({ id: `${id}-img${i + 1}`, src: photoUrl(k), alt, category })),
    amenities: input.amenities,
    policies: {
      checkIn: input.checkIn ?? "15:00",
      checkOut: input.checkOut ?? "11:00",
      children: input.children ?? "Children of all ages are welcome. Cots available on request.",
      pets: input.pets ?? "Pets are not allowed.",
      smoking: "Non-smoking property. Designated outdoor areas available.",
      payment: "Pay securely now with Oriel. The property may request a card for incidentals on arrival.",
      extraNotes: input.extraNotes,
    },
    nearby: input.nearby,
    rooms,
    badges: input.badges ?? [],
    popularity: input.popularity,
    categories: input.categories,
    contact: { phone: input.phone, email: `stay@${slug.replace(/-/g, "")}.example` },
    taxRate: input.taxRate,
    fees: (input.fees ?? []).map((f, i) => ({ ...f, id: `${id}-fee${i + 1}` })),
    deal: input.deal,
    createdAt: "2025-01-15T09:00:00.000Z",
  };
}

const cityTax = (amount: number, label = "City tourist tax"): Omit<MandatoryFee, "id"> => ({
  label,
  amount,
  per: "guest-night",
  payableAt: "property",
});

